def load_font(size: int) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    candidates = [
        "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
        "/System/Library/Fonts/PingFang.ttc",
        "/Library/Fonts/Arial Bold.ttf",
    ]
    for path in candidates:
        try:
            return ImageFont.truetype(path, size=size)
        except Exception:
            continue
    return ImageFont.load_default()


def draw_marker(draw: ImageDraw.ImageDraw, x: int, y: int, text: str, radius: int, font) -> None:
    draw.ellipse(
        [x - radius, y - radius, x + radius, y + radius],
        fill=(220, 0, 0),
        outline=(255, 255, 255),
        width=max(3, radius // 8),
    )
    bbox = draw.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    draw.text((x - tw / 2 - bbox[0], y - th / 2 - bbox[1]), text, fill=(255, 255, 255), font=font)


def render_image(src: Path, entries: list[dict]) -> Path:
    img = Image.open(src).convert("RGBA")
    w, h = img.size
    radius = max(16, min(24, round(min(w, h) * 0.028)))
    font = load_font(max(18, round(radius * 1.05)))
    draw = ImageDraw.Draw(img)
    for e in entries:
        x = round(e["cx"] / 1000 * w)
        y = round(e["cy"] / 1000 * h)
        draw_marker(draw, x, y, str(e["id"]), radius, font)
    dest = OUT_DIR / f"{src.stem}_标注.png"
    img.convert("RGB").save(dest, quality=95)
    return dest


def write_markdown(all_data: dict[str, list[dict]]) -> None:
    lines: list[str] = []
    lines.append("# 世界杯主题活动原型图标注说明\n")
    lines.append("> 标注方式：原图只添加红色编号圆点；说明文本单独在下方表格维护。坐标和元素归类基于当前截图视觉识别，后续写入钉钉文档前建议逐图复核。\n")
    for filename in sorted(all_data):
        entries = all_data[filename]
        if not entries:
            continue
        stem = Path(filename).stem
        lines.append(f"## {stem}\n")
        lines.append(f"![{stem} 标注图](标注/{stem}_标注.png)\n")
        lines.append("| 标号 | 图中内容 | 规则说明 |\n")
        lines.append("|---:|---|---|\n")
        for e in entries:
            lines.append(f"| {e['id']} | {e['visible']} | {e['rule']} |\n")
        lines.append("\n")
    (SRC_DIR / "图片内容规则说明.md").write_text("".join(lines), encoding="utf-8")


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    pngs = sorted(p for p in SRC_DIR.glob("*.png") if p.is_file())
    data: dict[str, list[dict]] = {}
    missing: list[str] = []
    for src in pngs:
        entries = ANNOTATIONS.get(src.name)
        if not entries:
            missing.append(src.name)
            continue
        render_image(src, entries)
        data[src.name] = entries
    (OUT_DIR / "annotations.json").write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    write_markdown(data)
    if missing:
        (OUT_DIR / "_missing.txt").write_text("\n".join(missing), encoding="utf-8")
    print(f"images={len(pngs)} annotated={len(data)} missing={len(missing)}")
    print(f"output={OUT_DIR}")
    print(f"rules={SRC_DIR / '图片内容规则说明.md'}")


if __name__ == "__main__":
    main()
